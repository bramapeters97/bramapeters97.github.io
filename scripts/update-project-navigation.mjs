const escape = text => text.replaceAll('&', '&amp;').replaceAll('"', '&quot;');
const link = ([label, href], page) => `<a href="${href}"${href === page ? ' aria-current="page"' : ''}>${escape(label)}</a>`;

function navigation(page) {
  const currentInMore = additional.some(([, href]) => href === page);
  return `<!-- Project navigation: generated by scripts/update-project-navigation.mjs -->
    <header class="project-nav" data-project-navigation>
      <nav class="project-nav-inner" aria-label="Primary">
        <a class="project-nav-home" href="index.html">${home}<span>Home</span></a>
        <button class="project-nav-toggle" type="button" aria-label="Open navigation menu" aria-controls="project-nav-menu" aria-expanded="false">
          <svg class="project-nav-icon" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path class="project-nav-menu-top" d="M4 6h16"/><path class="project-nav-menu-line" d="M4 12h16"/><path class="project-nav-menu-bottom" d="M4 18h16"/></svg>
        </button>
        <div class="project-nav-panel" id="project-nav-menu">
          <ul class="project-nav-projects">
            ${featured.map(item => `<li>${link(item, page)}</li>`).join('\n            ')}
            <li>
              <details class="project-nav-more${currentInMore ? ' has-current' : ''}">
                <summary>More projects<svg class="project-nav-icon project-nav-chevron" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="m6 9 6 6 6-6"/></svg></summary>
                <div class="project-nav-submenu">
                  ${additional.map(item => link(item, page)).join('\n                  ')}
                </div>
              </details>
            </li>
          </ul>
          <div class="project-nav-actions">
            <a href="https://www.linkedin.com/in/bram-peters/" target="_blank" rel="noopener noreferrer">${linkedin}<span>Bram Peters</span></a>
            <a href="https://www.linkedin.com/company/bram-peters-studio/" target="_blank" rel="noopener noreferrer">${linkedin}<span>Bram Peters Studios</span></a>
            <a class="project-nav-contact" href="mailto:bramapeters@outlook.com">${envelope}<span>Contact Me</span></a>
          </div>
        </div>
      </nav>
    </header>`;
}

let stale = false;
for (const page of pages) {
  const original = fs.readFileSync(page, 'utf8');
  const existing = /<!-- Project navigation: generated by scripts\/update-project-navigation.mjs -->[\s\S]*?<\/header>|<div class="nav-wrap"[^>]*>[\s\S]*?<\/nav>\s*<\/div>/;
  if (!existing.test(original)) throw new Error(`No project navigation found in ${page}`);
  let updated = original.replace(existing, navigation(page));
  if (!updated.includes('href="assets/css/project-navigation.css"')) {
    updated = updated.replace('</head>', '  <link rel="stylesheet" href="assets/css/project-navigation.css" />\n</head>');
  }
  if (!updated.includes('src="assets/js/project-navigation.js"')) {
    updated = updated.replace('</body>', '  <script src="assets/js/project-navigation.js" defer></script>\n</body>');
  }
  if (original !== updated) {
    stale = true;
    if (!process.argv.includes('--check')) fs.writeFileSync(page, updated);
    else console.error(`Project navigation is out of date: ${page}`);
  }
}
if (process.argv.includes('--check') && stale) process.exitCode = 1;
else console.log(`Project navigation ${process.argv.includes('--check') ? 'verified' : 'updated'} on ${pages.length} pages.`);
