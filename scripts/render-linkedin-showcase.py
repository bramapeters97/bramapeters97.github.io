"""Regenerate the native, JS-independent showcase after editing its JSON data."""
import json
from html import escape
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
START = '    <!-- LinkedIn showcase: generated by scripts/render-linkedin-showcase.py -->'
END = '    <!-- /LinkedIn showcase -->'
def icon(name):
    return f'<svg class="ui-icon" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><use href="#icon-{name}"></use></svg>'
def render(data):
    c = {k: escape(v, quote=True) for k, v in data['company'].items()}
    posts = []
    for raw in data['posts']:
        p = {k: escape(str(v), quote=True) if v is not None else None for k,v in raw.items()}
        credit = f'<p class="studio-credit">{p["collaborators"]}</p>' if p.get('collaborators') else ''
        attribution = f'<p class="studio-credit">{p["attribution"]}</p>' if p.get('attribution') else ''
        reactions = f'<small class="studio-reactions">♡ {p["reactionCount"]} reactions · checked <time datetime="{p["reactionCountVerifiedAt"]}">{p["reactionCountVerifiedAt"]}</time></small>' if raw.get('reactionCount') is not None and raw.get('reactionCountVerifiedAt') else ''
        posts.append(f'''          <article class="studio-post" aria-labelledby="studio-{p['id']}">
            <img class="studio-post-image" src="assets/img/linkedin/{p['image']}" alt="{p['alt']}" width="80" height="64" loading="lazy" decoding="async">
            <div><h4 id="studio-{p['id']}" lang="{p['lang']}">{p['title']}</h4>
              <p class="studio-excerpt" lang="{p['lang']}">{p['excerpt']}</p>
              {attribution}{credit}
              <a class="studio-post-link" href="{p['url']}" target="_blank" rel="noopener noreferrer" aria-label="Open {p['title']} on LinkedIn (new tab)">Open on LinkedIn <span aria-hidden="true">↗</span></a>{reactions}
            </div>
          </article>''')
    return f'''{START}
    <section id="linkedin-showcase" class="linkedin-showcase" aria-labelledby="studio-title">
      <div class="studio-company">
        <img class="studio-cover" src="assets/img/linkedin/cover.jpg" alt="Bram Peters Studio projects: analytics, transit design, apps, web and video production" width="1440" height="243" loading="lazy" decoding="async">
        <div class="studio-identity">
          <img class="studio-logo" src="assets/img/linkedin/logo.jpg" alt="Bram Peters Studio logo" width="50" height="50" loading="lazy" decoding="async">
          <svg class="studio-linkedin" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><use href="#icon-linkedin"></use></svg>
          <div><h2 id="studio-title">{c['name']}</h2><p class="studio-tagline">{c['tagline']}</p></div>
        </div>
        <p class="studio-description">{c['description']}</p>
        <div class="studio-footer">
          <p class="studio-details"><span>{icon('web')} Amsterdam</span><span>{icon('grid')} Founded 2026</span></p>
          <a class="studio-cta" href="{c['url']}" target="_blank" rel="noopener noreferrer" aria-label="View Bram Peters Studio company on LinkedIn (new tab)">View company on LinkedIn <span aria-hidden="true">↗</span></a>
        </div>
      </div>
      <div class="studio-featured">
        <h3>{icon('app')} Featured Posts</h3>
{chr(10).join(posts)}
      </div>
    </section>
{END}'''
if __name__ == '__main__':
    page = ROOT / 'index.html'
    html = page.read_text()
    block = render(json.loads((ROOT / 'assets/linkedin-showcase.json').read_text()))
    if START in html:
        before, rest = html.split(START, 1)
        _, after = rest.split(END, 1)
        html = before + block + after
    else:
        html = html.replace('    <div class="portfolio-layout">', block + '\n    <div class="portfolio-layout">', 1)
    stylesheet = '  <link rel="stylesheet" href="assets/css/linkedin-showcase.css" />'
    if stylesheet not in html:
        html = html.replace('</head>', stylesheet + '\n</head>', 1)
    page.write_text(html)
